"""
core/memory/episodic.py

Episodic memory for NyxAI — a journal of notable events and actions.

Episodic memories record what happened during sessions:
  - Tool executions ("Opened VS Code at 10:30 AM")
  - Session starts
  - User actions that were completed
  - Significant conversation moments

Unlike long-term memories (user-approved facts), episodic memories are
auto-generated by the system. They provide a searchable activity log
that can be used for context recall in future conversations.

Example episodic events:
  event_type: "tool_execution"
  description: "Opened application: code (VS Code)"
  metadata: {"tool": "open_application", "args": {"application": "code"}}
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

from core.logging import get_logger
from core.memory.database import MemoryDatabase

logger = get_logger(__name__)


def _utcnow() -> str:
    """Return the current UTC time as an ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat()


# Known episodic event type constants
class EventType:
    TOOL_EXECUTION = "tool_execution"
    SESSION_START = "session_start"
    SESSION_END = "session_end"
    USER_ACTION = "user_action"
    SYSTEM_EVENT = "system_event"


class EpisodicMemory:
    """
    Records and retrieves notable events during NyxAI sessions.

    Events are auto-generated by the agent when tools execute or when
    significant session events occur. They are stored in the
    `episodic_memories` SQLite table.

    Args:
        db: Initialized MemoryDatabase instance.
    """

    def __init__(self, db: MemoryDatabase) -> None:
        self._db = db

    async def record_event(
        self,
        event_type: str,
        description: str,
        conversation_id: str | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> int:
        """
        Record a notable event in the episodic memory journal.

        Args:
            event_type: Category of event (use EventType constants).
            description: Human-readable description of what happened.
            conversation_id: Optional UUID of the associated conversation.
            metadata: Optional dict of extra structured data (tool args, etc.).

        Returns:
            The integer ID of the new episodic memory row.
        """
        metadata_json = json.dumps(metadata or {})
        now = _utcnow()

        async with self._db.connection() as conn:
            cursor = await conn.execute(
                """
                INSERT INTO episodic_memories
                    (conversation_id, event_type, description, metadata, created_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (conversation_id, event_type, description, metadata_json, now),
            )
            event_id = cursor.lastrowid
            await conn.commit()

        logger.debug(
            "episodic_event_recorded",
            event_id=event_id,
            event_type=event_type,
            conversation_id=conversation_id,
        )
        return event_id  # type: ignore[return-value]

    async def record_tool_execution(
        self,
        tool_name: str,
        description: str,
        conversation_id: str | None = None,
        tool_args: dict[str, Any] | None = None,
        tool_result: dict[str, Any] | None = None,
    ) -> int:
        """
        Convenience method to record a tool execution event.

        Args:
            tool_name: Name of the tool that was called.
            description: Human-readable description (e.g. "Opened Firefox").
            conversation_id: Optional conversation UUID.
            tool_args: Arguments passed to the tool.
            tool_result: Result returned by the tool.

        Returns:
            The integer ID of the new episodic memory row.
        """
        metadata = {
            "tool": tool_name,
            "args": tool_args or {},
            "result_summary": str(tool_result)[:200] if tool_result else None,
        }
        return await self.record_event(
            event_type=EventType.TOOL_EXECUTION,
            description=description,
            conversation_id=conversation_id,
            metadata=metadata,
        )

    async def get_recent(
        self,
        limit: int = 20,
        event_type: str | None = None,
        conversation_id: str | None = None,
    ) -> list[dict]:
        """
        Return recent episodic events, newest first.

        Args:
            limit: Maximum number of events to return.
            event_type: Optional filter by event type.
            conversation_id: Optional filter by conversation.

        Returns:
            List of event dicts with id, conversation_id, event_type,
            description, metadata (parsed dict), and created_at.
        """
        conditions = []
        params: list[Any] = []

        if event_type:
            conditions.append("event_type = ?")
            params.append(event_type)
        if conversation_id:
            conditions.append("conversation_id = ?")
            params.append(conversation_id)

        where_clause = f"WHERE {' AND '.join(conditions)}" if conditions else ""
        params.append(limit)

        async with self._db.connection() as conn:
            cursor = await conn.execute(
                f"""
                SELECT id, conversation_id, event_type, description, metadata, created_at
                FROM episodic_memories
                {where_clause}
                ORDER BY id DESC
                LIMIT ?
                """,
                params,
            )
            rows = await cursor.fetchall()

        result = []
        for row in rows:
            event = dict(row)
            # Parse metadata JSON back to dict
            try:
                event["metadata"] = json.loads(event["metadata"])
            except (json.JSONDecodeError, TypeError):
                event["metadata"] = {}
            result.append(event)

        return result

    async def get_session_summary(self, conversation_id: str) -> str:
        """
        Return a short human-readable summary of events in a conversation.

        Used for context injection when resuming a conversation.

        Args:
            conversation_id: UUID string of the conversation.

        Returns:
            Multiline string like:
                "- Opened VS Code
                 - Searched YouTube for AI tutorials"
            Returns empty string if no events.
        """
        events = await self.get_recent(
            limit=10,
            conversation_id=conversation_id,
        )
        if not events:
            return ""

        lines = [f"- {e['description']}" for e in reversed(events)]
        return "\n".join(lines)

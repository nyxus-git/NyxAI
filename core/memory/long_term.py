"""
core/memory/long_term.py

Long-term memory for NyxAI — persistent user facts and preferences.

Long-term memories are user-approved facts that NyxAI should always
remember across all conversations and restarts. They are injected into
the system prompt as a "What I know about you" section so the LLM always
has this context available.

Examples of long-term memories:
  - "User prefers Hinglish responses."
  - "User is working on the NyxAI project."
  - "User uses Arch Linux with Hyprland."
  - "User likes concise answers."

Memories can be:
  - Added manually via the UI or API
  - Auto-generated by the agent when it detects important user information
  - Tagged for filtering and organization
"""

from __future__ import annotations

from datetime import datetime, timezone

from core.logging import get_logger
from core.memory.database import MemoryDatabase

logger = get_logger(__name__)


def _utcnow() -> str:
    """Return the current UTC time as an ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat()


class LongTermMemory:
    """
    CRUD manager for long-term user memories stored in SQLite.

    All memories are fetched at chat time and injected into the LLM
    system prompt. The user can view, add, and delete memories via
    the /memory/long-term API endpoints.

    Args:
        db: Initialized MemoryDatabase instance.
    """

    def __init__(self, db: MemoryDatabase) -> None:
        self._db = db

    async def add_memory(
        self,
        content: str,
        source: str = "manual",
        tags: list[str] | None = None,
    ) -> int:
        """
        Store a new long-term memory.

        Args:
            content: The fact or preference to remember. Plain text.
            source: Origin of the memory: 'manual', 'auto', or 'conversation'.
            tags: Optional list of tags for filtering (e.g. ["preference", "project"]).

        Returns:
            The integer ID of the newly created memory row.
        """
        tags_str = ",".join(tags) if tags else ""
        now = _utcnow()
        async with self._db.connection() as conn:
            cursor = await conn.execute(
                """
                INSERT INTO long_term_memories (content, source, tags, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (content, source, tags_str, now, now),
            )
            memory_id = cursor.lastrowid
            await conn.commit()

        logger.info(
            "long_term_memory_added",
            memory_id=memory_id,
            source=source,
            tags=tags_str,
        )
        return memory_id  # type: ignore[return-value]

    async def get_all(self, tag: str | None = None) -> list[dict]:
        """
        Return all long-term memories, optionally filtered by tag.

        Args:
            tag: If provided, only return memories containing this tag.

        Returns:
            List of memory dicts with id, content, source, tags,
            created_at, updated_at fields.
        """
        async with self._db.connection() as conn:
            if tag:
                cursor = await conn.execute(
                    """
                    SELECT id, content, source, tags, created_at, updated_at
                    FROM long_term_memories
                    WHERE ',' || tags || ',' LIKE ?
                    ORDER BY created_at DESC
                    """,
                    (f"%,{tag},%",),
                )
            else:
                cursor = await conn.execute(
                    """
                    SELECT id, content, source, tags, created_at, updated_at
                    FROM long_term_memories
                    ORDER BY created_at DESC
                    """
                )
            rows = await cursor.fetchall()

        return [dict(row) for row in rows]

    async def delete_memory(self, memory_id: int) -> bool:
        """
        Delete a specific long-term memory by ID.

        Args:
            memory_id: The integer primary key of the memory to delete.

        Returns:
            True if a row was deleted, False if the ID was not found.
        """
        async with self._db.connection() as conn:
            cursor = await conn.execute(
                "DELETE FROM long_term_memories WHERE id = ?",
                (memory_id,),
            )
            deleted = cursor.rowcount > 0
            await conn.commit()

        if deleted:
            logger.info("long_term_memory_deleted", memory_id=memory_id)
        else:
            logger.warning("long_term_memory_not_found", memory_id=memory_id)

        return deleted

    async def update_memory(self, memory_id: int, content: str) -> bool:
        """
        Update the content of an existing long-term memory.

        Args:
            memory_id: The integer ID of the memory to update.
            content: New content string.

        Returns:
            True if updated, False if not found.
        """
        now = _utcnow()
        async with self._db.connection() as conn:
            cursor = await conn.execute(
                "UPDATE long_term_memories SET content = ?, updated_at = ? WHERE id = ?",
                (content, now, memory_id),
            )
            updated = cursor.rowcount > 0
            await conn.commit()

        if updated:
            logger.info("long_term_memory_updated", memory_id=memory_id)
        return updated

    async def format_for_prompt(self) -> str:
        """
        Return a formatted string of all memories suitable for injection
        into the system prompt.

        Returns empty string if there are no memories, so callers can
        check `if formatted_memories:` before appending to the prompt.

        Returns:
            Multiline string like:
                ## What I Know About You
                - User prefers Hinglish responses.
                - User is working on NyxAI project.
        """
        memories = await self.get_all()
        if not memories:
            return ""

        lines = ["## What I Know About You"]
        for mem in memories:
            lines.append(f"- {mem['content']}")

        return "\n".join(lines)
